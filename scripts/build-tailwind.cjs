// Compiles Tailwind at build time into tailwind-styles.html (an HtmlService include).
// No runtime CDN. `--check` fails when the committed file is stale.
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const cli = path.join(root, 'node_modules', '@tailwindcss', 'cli', 'dist', 'index.mjs');
const tmp = path.join(require('node:os').tmpdir(), 'capstone-tailwind-' + process.pid + '.css');
execFileSync(process.execPath, [cli, '-i', path.join(__dirname, 'tailwind-input.css'), '-o', tmp, '--minify'], { cwd: root, stdio: 'pipe' });
const css = fs.readFileSync(tmp, 'utf8').trim();
fs.unlinkSync(tmp);
if (css.includes('</style')) throw new Error('Compiled CSS must not contain </style.');
const output = '<!-- Generated by npm run build:tailwind from scripts/tailwind-input.css. Do not edit. -->\n<style>\n' + css + '\n</style>\n';
const target = path.join(root, 'tailwind-styles.html');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) throw new Error('Run npm run build:tailwind to regenerate tailwind-styles.html.');
  console.log('tailwind-styles.html verified.');
} else {
  fs.writeFileSync(target, output);
  console.log('tailwind-styles.html generated (' + output.length + ' bytes).');
}
